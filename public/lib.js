// Shared frontend helpers: API client, DOM utils, escaping, toasts.

const API = '/api/v1';

/** Minimal fetch wrapper with consistent error handling. */
export async function apiFetch(path, options = {}) {
  const res = await fetch(API + path, {
    headers: { 'Content-Type': 'application/json' },
    ...options,
  });
  let data = null;
  try {
    data = await res.json();
  } catch {
    /* non-JSON response */
  }
  if (!res.ok) {
    const msg = data?.error?.message || `Request failed (${res.status})`;
    throw new Error(msg);
  }
  return data;
}

/** Escape text for safe insertion into HTML (prevents XSS from any source). */
export function esc(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

/** Create a DOM element from an HTML string (first element). */
export function el(html) {
  const t = document.createElement('template');
  t.innerHTML = html.trim();
  return t.content.firstElementChild;
}

/** Map a backend risk category to a CSS badge class. */
export function categoryClass(category) {
  switch (category) {
    case 'Low Risk Indicators': return 'low';
    case 'Suspicious': return 'suspicious';
    case 'High Risk Indicators': return 'high';
    default: return 'unknown';
  }
}

/** Color for the score meter (also conveyed by text/badge, never color alone). */
export function meterColor(category) {
  switch (category) {
    case 'Low Risk Indicators': return 'var(--ok)';
    case 'Suspicious': return 'var(--warn)';
    case 'High Risk Indicators': return 'var(--danger)';
    default: return 'var(--unknown)';
  }
}

export function badge(category) {
  return `<span class="badge ${categoryClass(category)}">${esc(category)}</span>`;
}

export function formatDate(iso) {
  if (!iso) return '—';
  const d = new Date(iso);
  return d.toLocaleString();
}

/** Toast notification. */
export function toast(message, type = 'info') {
  const container = document.getElementById('toasts');
  const node = el(`<div class="toast ${type}" role="status">${esc(message)}</div>`);
  container.appendChild(node);
  setTimeout(() => {
    node.style.opacity = '0';
    node.style.transition = 'opacity 0.3s';
    setTimeout(() => node.remove(), 320);
  }, 4000);
}

/** Promise-based confirmation dialog. */
export function confirmDialog(title, message, okLabel = 'Confirm') {
  return new Promise((resolve) => {
    const dlg = document.getElementById('confirm-dialog');
    document.getElementById('confirm-title').textContent = title;
    document.getElementById('confirm-message').textContent = message;
    const okBtn = document.getElementById('confirm-ok');
    okBtn.textContent = okLabel;
    const cancelBtn = document.getElementById('confirm-cancel');

    const cleanup = (result) => {
      okBtn.removeEventListener('click', onOk);
      cancelBtn.removeEventListener('click', onCancel);
      dlg.removeEventListener('cancel', onCancel);
      dlg.close();
      resolve(result);
    };
    const onOk = () => cleanup(true);
    const onCancel = () => cleanup(false);

    okBtn.addEventListener('click', onOk);
    cancelBtn.addEventListener('click', onCancel);
    dlg.addEventListener('cancel', onCancel);
    dlg.showModal();
  });
}

/** Render a list of findings. */
export function renderFindings(findings) {
  if (!findings || findings.length === 0) {
    return `<p class="muted">No specific indicators were detected.</p>`;
  }
  return findings
    .map(
      (f) => `
      <div class="finding">
        <span class="sev ${esc(f.severity)}">${esc(f.severity)}</span>
        <div>
          <div class="ftitle">${esc(f.title)}</div>
          <div class="fexp">${esc(f.explanation)}</div>
        </div>
      </div>`,
    )
    .join('');
}

/** Render the full analysis result panel (shared by URL + message views). */
export function renderResult(analysis) {
  if (!analysis.valid) {
    return `
      <div class="card mt">
        <div class="row space-between mb">
          <h2 class="section" style="margin:0">Analysis</h2>
          ${badge(analysis.category)}
        </div>
        <p class="muted">${esc(analysis.reason || 'Could not analyze the input.')}</p>
      </div>`;
  }

  const ai = analysis.aiExplanation
    ? `<div class="card mt">
         <h2 class="section">AI explanation
           <span class="faint">(generated by ${esc(analysis.aiExplanation.model || 'a model')})</span>
         </h2>
         <p class="muted">${esc(analysis.aiExplanation.text)}</p>
       </div>`
    : '';

  const rep = analysis.reputation && analysis.reputation.available
    ? `<p class="faint">Reputation source: ${esc(analysis.reputation.source)} (checked ${formatDate(analysis.reputation.checkedAt)})</p>`
    : (analysis.reputation
        ? `<p class="faint">${esc(analysis.reputation.note)}</p>`
        : '');

  const embedded = analysis.embeddedUrls && analysis.embeddedUrls.length
    ? `<div class="mt">
         <h3 style="font-size:0.95rem">Links found in the message</h3>
         ${analysis.embeddedUrls.map((u) => `
           <div class="row space-between" style="padding:6px 0;border-bottom:1px solid var(--border)">
             <span style="word-break:break-all">${esc(u.url)}</span>
             ${badge(u.category)}
           </div>`).join('')}
       </div>`
    : '';

  return `
    <div class="card mt">
      <div class="row space-between mb">
        <h2 class="section" style="margin:0">Analysis result</h2>
        ${badge(analysis.category)}
      </div>

      ${analysis.normalizedUrl ? `<p class="faint" style="word-break:break-all">Analyzed: ${esc(analysis.normalizedUrl)}</p>` : ''}

      <div class="row space-between mb">
        <span class="muted">Indicator score
          <span class="tip" data-tip="${esc(analysis.scoreMeaning)}" tabindex="0">(?)</span>
        </span>
        <strong>${esc(analysis.score)}/100</strong>
      </div>
      <div class="meter mb"><span style="width:${esc(analysis.score)}%;background:${meterColor(analysis.category)}"></span></div>

      <h3 style="font-size:0.95rem">Why</h3>
      ${renderFindings(analysis.findings)}

      ${embedded}

      <h3 style="font-size:0.95rem" class="mt">Recommended next steps</h3>
      <ul class="rec-list">
        ${analysis.recommendations.map((r) => `<li>${esc(r)}</li>`).join('')}
      </ul>

      <div class="disclaimer mt">${esc(analysis.confidenceNote)}</div>
      ${rep}
    </div>
    ${ai}`;
}

export function emptyState(text, actionHtml = '') {
  return `
    <div class="empty">
      <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5">
        <path d="M12 2 4 5v6c0 5 3.4 8.5 8 11 4.6-2.5 8-6 8-11V5z"/>
      </svg>
      <p>${esc(text)}</p>
      ${actionHtml}
    </div>`;
}
